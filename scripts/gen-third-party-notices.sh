#!/bin/sh
# Regenerate THIRD_PARTY_NOTICES.md from the modules linked into the jotaro CLI.
#
# MIT, BSD and Apache-2.0 require the copyright notice and the license text to ship with
# binaries, so the release archives include this file (see .goreleaser.yaml).
# Run it again whenever go.mod changes: scripts/gen-third-party-notices.sh
set -eu

cd "$(dirname "$0")/.."
out=THIRD_PARTY_NOTICES.md

{
	echo "# Third-party notices"
	echo
	echo "The \`jotaro\` binary includes the following third-party modules."
	echo "jotaro itself is licensed under the MIT License (see LICENSE)."
	echo "This file is generated by scripts/gen-third-party-notices.sh."

	go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}} {{.Dir}}{{end}}{{end}}' ./cmd/jotaro |
		sort -u |
		while read -r path version dir; do
			file=$(ls "$dir" | grep -i -m1 -E '^(licen[cs]e|copying)') || {
				echo "no license file found for $path" >&2
				exit 1
			}
			echo
			echo "## $path $version"
			echo
			echo '```text'
			cat "$dir/$file"
			echo '```'
		done
} >"$out.tmp"
mv "$out.tmp" "$out"
